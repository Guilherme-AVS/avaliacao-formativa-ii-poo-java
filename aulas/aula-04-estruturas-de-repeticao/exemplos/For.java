public class For {

    public static void main(String[] args) {

        for (int contador = 1; contador <= 5; contador++) {
            System.out.println("Contador: " + contador);
        }

        System.out.println();

        for (int i = 10; i >= 1; i--) {
            System.out.println("Contagem regressiva: " + i);
        }
    }
}
