public class TiposPrimitivos {

    public static void main(String[] args) {
        byte idade = 20;
        short ano = 2026;
        int populacao = 1000000;
        long distancia = 9000000000L;

        float altura = 1.75f;
        double salario = 3500.50;

        char inicial = 'I';
        boolean aprovado = true;

        System.out.println("byte: " + idade);
        System.out.println("short: " + ano);
        System.out.println("int: " + populacao);
        System.out.println("long: " + distancia);
        System.out.println("float: " + altura);
        System.out.println("double: " + salario);
        System.out.println("char: " + inicial);
        System.out.println("boolean: " + aprovado);
    }
}
